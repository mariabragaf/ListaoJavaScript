let estação = 1;

switch (estação) {
    case 1:
        console.log('verão');
        break;
    case 2:
        console.log('outono');
        break;
    case 3:
        console.log('inverno');
        break;
    case 4:
        console.log('primavera');
        break;
    default:
        console.log('estação inválida');

}